#!/usr/bin/env node
// Regenerates src/domain/reactionDigests.generated.ts from public/abyssal-emojis.
// The digests ship inside the release-verified JavaScript bundle, so reaction
// images can be authenticated when they are first displayed instead of being
// downloaded by the startup audit.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const directory = resolve(root, "public/abyssal-emojis");
const target = resolve(root, "src/domain/reactionDigests.generated.ts");

const entries = readdirSync(directory)
  .filter((name) => /\.(gif|png)$/i.test(name))
  .sort()
  .map((name) => {
    const bytes = readFileSync(resolve(directory, name));
    const sha256Hex = createHash("sha256").update(bytes).digest("hex");
    return `  ${JSON.stringify(name)}: { sha256Hex: "${sha256Hex}", size: ${bytes.byteLength} },`;
  });

writeFileSync(target, `// Generated by scripts/generate-reaction-digests.mjs. Do not edit.
export interface ReactionDigest {
  readonly sha256Hex: string;
  readonly size: number;
}

export const REACTION_DIGESTS: Readonly<Record<string, ReactionDigest>> = Object.freeze({
${entries.join("\n")}
});
`);
